export type MessageKey = keyof typeof messages.ko;
export type NestedMessageKey<T> = T extends object 
  ? { [K in keyof T]: T[K] extends object 
      ? `${string & K}.${NestedMessageKey<T[K]>}` 
      : string & K 
    }[keyof T]
  : never;

export type AllMessageKeys = NestedMessageKey<typeof messages.ko>;

export function getMessage(
  locale: 'ko' | 'en', 
  key: string, 
  fallback?: string
): string {
  const keys = key.split('.');
  let message: any = messages[locale];
  
  for (const k of keys) {
    message = message?.[k];
    if (message === undefined) break;
  }
  
  return message || fallback || key;
}